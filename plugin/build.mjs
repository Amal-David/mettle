import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {join,dirname} from 'node:path';
const root=dirname(fileURLToPath(import.meta.url));
const compiler=(await readFile(join(root,'src/compiler.mjs'),'utf8')).replace(/^export /gm,'');
const capture=(await readFile(join(root,'src/capture.mjs'),'utf8')).replace(/^export /gm,'');
const host=await readFile(join(root,'src/plugin.js'),'utf8');
const code=`/* FigmaMetal v0.2; generated by build.mjs. No dependencies. */\nconst FM=(()=>{\n${compiler}\nreturn {compileScene,compileTransition};\n})();\nconst FMC=(()=>{\n${capture}\nreturn {createCapture};\n})();\n${host}`;
await writeFile(join(root,'code.js'),code);
console.log('Built plugin/code.js; import plugin/manifest.json in Figma Desktop.');
